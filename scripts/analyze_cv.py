"""Draft a candidate profile from a CV, without inventing anything.

Reads .tex, .md or .txt CV files (a single file, or a folder of variants) and
records only what the text literally contains. A skill the CV does not mention
is not added, and a job requirement is never turned into a candidate skill.

The output is a DRAFT for the user to review. It is written to
data/profile.draft.json and never overwrites data/profile.json.
"""

from __future__ import annotations

import re
from pathlib import Path

from tracker import normalize

_READABLE = {".tex", ".md", ".txt"}

_SECTIONS = {
    "education": ("education", "academic"),
    "experience": ("experience", "employment", "work history"),
    "projects": ("projects", "personal projects", "selected projects"),
    "skills": ("skills", "technical skills", "technologies"),
}

_FRAMEWORKS = {"React", "Next.js", "Vue", "Angular", "Django", "Flask", "FastAPI",
               "Spring", "Spring Boot", "Node.js", "Tkinter"}
_LIBRARIES = {"PyTorch", "TensorFlow", "Keras", "scikit-learn", "NumPy", "pandas",
              "OpenCV", "YOLO"}
_SYSTEMS = {"Linux", "Git", "GitLab", "GitHub", "Docker", "Kubernetes", "AWS", "Azure",
            "GCP", "Terraform", "CMake", "PostgreSQL", "MySQL", "MongoDB", "Redis",
            "Kafka", "Spark", "Hadoop", "Airflow", "dbt"}
_HARDWARE = {"Arduino", "Raspberry Pi", "FPGA", "RISC-V", "Verilog", "SystemVerilog", "VHDL"}
_ML = {"PyTorch", "TensorFlow", "Keras", "scikit-learn", "OpenCV", "YOLO", "CUDA"}


def analyze(path: Path) -> dict:
    """Build a draft profile dict from a CV file or folder of variants."""
    path = Path(path)
    files = _collect(path)
    if not files:
        raise ValueError(
            f"No readable CV files at {path}. Looked for {sorted(_READABLE)}. "
            "PDF and DOCX are not read here - export to text first."
        )

    text = "\n".join(_read(f) for f in files)
    _, languages, technologies = normalize.extract_skills(text)

    sections = _split_sections(text)

    # A skill named inside a project or experience section carries stronger
    # evidence than one appearing only in a skills list. That distinction is
    # the whole point: it is what stops a keyword becoming a claimed strength.
    evidence_text = sections.get("projects", "") + sections.get("experience", "")
    evidenced, _, _ = normalize.extract_skills(evidence_text)
    evidenced_set = set(evidenced)
    source_note = ", ".join(f.name for f in files[:3])

    def entry(name: str) -> dict:
        return {
            "name": name,
            "evidence": "project" if name in evidenced_set else "coursework",
            "source": source_note,
        }

    tech = set(technologies)
    return {
        "_README": [
            "DRAFT generated by scripts/analyze_cv.py from the files in _sources.",
            "Nothing here was inferred beyond what the CV text literally contains.",
            "Review every entry, correct the evidence levels, fill in the blanks,",
            "then copy this over data/profile.json and set profile_configured to true.",
            "evidence 'project' = the skill appeared in a project or experience section.",
            "evidence 'coursework' = it appeared only in a skills list. Upgrade to",
            "'demonstrated' or 'professional' only where that is genuinely true.",
        ],
        "_sources": [str(f) for f in files],
        "profile_configured": False,
        "degree": _find_degree(sections.get("education", "") or text),
        "university": _find_university(text),
        "graduation_year": _find_graduation_year(sections.get("education", "") or text),
        "current_year": None,
        "expected_classification": "",
        "eligible_role_types": [],
        "languages": [entry(s) for s in sorted(set(languages))],
        "frameworks": [entry(s) for s in sorted(tech & _FRAMEWORKS)],
        "libraries": [entry(s) for s in sorted(tech & _LIBRARIES)],
        "systems": [entry(s) for s in sorted(tech & _SYSTEMS)],
        "hardware": [entry(s) for s in sorted(tech & _HARDWARE)],
        "machine_learning": [entry(s) for s in sorted(tech & _ML)],
        "coursework": [],
        "projects": [{"name": n, "technologies": []} for n in _entries(sections.get("projects", ""))[:12]],
        "experience": [{"role": n, "technologies": []} for n in _entries(sections.get("experience", ""))[:12]],
        "achievements": [],
        "domain_knowledge": [],
        "preferred_locations": [],
        "preferred_industries": [],
        "work_authorisation": {"requires_visa_sponsorship": None, "right_to_work_uk": None},
        "constraints": {"earliest_start": "", "latest_end": "",
                        "min_duration_weeks": None, "max_duration_weeks": None},
        "_uncertain": [
            "current_year - a CV rarely states this unambiguously; fill it in by hand",
            "evidence levels - verify each against the actual CV before trusting a score",
            "project technologies - left empty rather than guessed from nearby text",
        ],
    }


def _collect(path: Path) -> list[Path]:
    if path.is_file():
        return [path] if path.suffix.lower() in _READABLE else []
    return sorted(
        f for f in path.iterdir()
        if f.is_file() and f.suffix.lower() in _READABLE and not f.name.startswith("_")
    )


def _read(path: Path) -> str:
    text = path.read_text(encoding="utf-8", errors="replace")
    if path.suffix.lower() == ".tex":
        text = re.sub(r"%.*", " ", text)                            # comments
        text = re.sub(r"\\[a-zA-Z]+\*?(\[[^\]]*\])?", " ", text)    # commands
        text = text.replace("{", " ").replace("}", " ")
    return text


def _split_sections(text: str) -> dict[str, str]:
    """Split on heading words. Crude, but it only has to tell a skills list
    from a projects list, which is all the evidence levels depend on."""
    out: dict[str, list[str]] = {}
    current: str | None = None

    for line in text.splitlines():
        stripped = line.strip().casefold().strip("#*_ :")
        if len(stripped) < 40:
            matched = next(
                (key for key, words in _SECTIONS.items()
                 if any(stripped == w or stripped.startswith(w) for w in words)),
                None,
            )
            if matched:
                current = matched
                out.setdefault(current, [])
                continue
        if current:
            out[current].append(line)

    return {key: "\n".join(value) for key, value in out.items()}


def _entries(section: str) -> list[str]:
    """Entry titles within a section: short lines that are not bullets."""
    names = []
    for raw in section.splitlines():
        line = raw.strip(" \t-*|")
        if 4 < len(line) < 80 and not raw.strip().startswith(("-", "*")):
            if re.search(r"[A-Za-z]", line) and line.count(" ") < 9:
                cleaned = normalize.clean_text(line, limit=80)
                if cleaned:
                    names.append(cleaned)
    return list(dict.fromkeys(names))


def _find_degree(text: str) -> str:
    match = re.search(
        r"\b((?:B\.?Sc|M\.?Sc|M\.?Eng|B\.?Eng|BA|MA|PhD|Bachelor|Master)[^\n,;]{0,60})",
        text, flags=re.IGNORECASE,
    )
    return normalize.clean_text(match.group(1), limit=120) if match else ""


def _find_university(text: str) -> str:
    match = re.search(r"\b((?:University|Imperial|UCL|Oxford|Cambridge)[^\n,;]{0,60})", text)
    return normalize.clean_text(match.group(1), limit=120) if match else ""


def _find_graduation_year(text: str) -> int | None:
    """The latest plausible year in the education section, which is the
    expected graduation year on almost every CV layout."""
    years = [int(y) for y in re.findall(r"\b(20[2-4]\d)\b", text)]
    return max(years) if years else None


if __name__ == "__main__":
    import json
    import sys

    if len(sys.argv) < 2:
        print("usage: python -m scripts.analyze_cv <cv file or folder>")
        raise SystemExit(2)
    print(json.dumps(analyze(Path(sys.argv[1])), indent=2))
